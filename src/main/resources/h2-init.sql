CREATE TABLE IF NOT EXISTS usermaster (userid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, firstname VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, gender CHAR(1) NOT NULL, phone VARCHAR(30) NOT NULL, address VARCHAR(500), usertype SMALLINT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS locations (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, location VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS provider (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS flightmaster (flightid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, flightnumber VARCHAR(20) NOT NULL UNIQUE, provider VARCHAR(120) NOT NULL, source VARCHAR(120) NOT NULL, destination VARCHAR(120) NOT NULL, duration VARCHAR(40) NOT NULL, price DECIMAL(10,2) NOT NULL CHECK (price >= 0), createddate TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, CHECK (source <> destination));
CREATE TABLE IF NOT EXISTS bookingmaster (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flightid INT NOT NULL REFERENCES flightmaster(flightid),
    userid INT NOT NULL REFERENCES usermaster(userid),
    flightdate DATE NOT NULL,
    flighttime TIME NOT NULL,
    passenger_name VARCHAR(120),
    passport_no VARCHAR(40),
    nationality VARCHAR(60),
    dob VARCHAR(30),
    gender VARCHAR(10),
    seat VARCHAR(10),
    cabin_class VARCHAR(30),
    meal VARCHAR(50),
    contact_phone VARCHAR(30),
    contact_email VARCHAR(254),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS contactus (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL, message CLOB NOT NULL, userid INT NOT NULL REFERENCES usermaster(userid), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
